def fold_hanzi(value: str) -> str:
    """Map traditional C-pop characters onto simplified so 鄧麗君 matches 邓丽君."""
    return (value or "").translate(_TRAD_TO_SIMP)


def hanzi_variants(value: str) -> tuple[str, ...]:
    """Original plus simplified form when they differ. Never rewrite kana."""
    text = (value or "").strip()
    if not text:
        return ()
    folded = fold_hanzi(text)
    if folded == text:
        return (text,)
    return (text, folded)
